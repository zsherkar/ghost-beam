DATA_SOURCE_REGISTRY_VERSION = "0.1.0"
FEDERATED_SAFETY_DISCLOSURE = (
    "The live Ghost Beam demo uses the local synthetic JAX twin. External sources are "
    "read-only local importers, manifests, validation layers, provenance standards, or "
    "future connector stubs. No external source can write to hardware."
)


def backend_root() -> Path:
    return Path(__file__).resolve().parents[1]


def project_root() -> Path:
    return backend_root().parent


def public_datasets_root() -> Path:
    return backend_root() / "data" / "public_datasets"


def standards_root() -> Path:
    return backend_root() / "data" / "standards"


def boostr_manifest_path() -> Path:
    return public_datasets_root() / "boostr_manifest.json"


def fermilab_bpm_ipm_manifest_path() -> Path:
    return public_datasets_root() / "fermilab_bpm_ipm_manifest.json"


def materials_project_manifest_path() -> Path:
    return public_datasets_root() / "materials_project_context_manifest.json"


def openpmd_manifest_path() -> Path:
    return standards_root() / "openpmd_compatibility_manifest.json"


def workflowhub_manifest_path() -> Path:
    return standards_root() / "workflowhub_compatibility_manifest.json"


def synthetic_manifest_path() -> Path:
    return backend_root() / "data" / "synthetic_data_manifest.json"


def recorded_fixture_manifest_path() -> Path:
    return backend_root() / "data" / "recorded_runs" / "sample_recorded_drifted_twin_manifest.json"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def load_json(path: Path) -> dict[str, Any] | None:
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def frictionless_validation_report() -> dict[str, Any]:
    installed = importlib.util.find_spec("frictionless") is not None
    return {
        "standard_id": "frictionless",
        "name": "Frictionless Data validation",
        "status": "available" if installed else "not_installed",
        "validated_targets": [],
        "validation_errors": [],
        "note": (
            "Frictionless is installed and can validate tabular artifacts."
            if installed
            else "Frictionless is not installed; evidence bundle includes manifest-level validation status only."
        ),
    }


def _source(
    *,
    source_id: str,
    name: str,
    category: str,
    role: str,
    status: str,
    active: bool,
    writes_allowed: bool | str = False,
    local_only: bool = True,
    runtime_network_required: bool = False,
    doi: str | None = None,
    license: str | None = None,
    expected_format: str | None = None,
    description: str,
    safety_disclosure: str = FEDERATED_SAFETY_DISCLOSURE,
    manifest_path: Path | None = None,
    metadata: dict[str, Any] | None = None,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "id": source_id,
        "name": name,
        "category": category,
        "role": role,
        "status": status,
        "active": active,
        "writes_allowed": writes_allowed,
        "local_only": local_only,
        "runtime_network_required": runtime_network_required,
        "description": description,
        "safety_disclosure": safety_disclosure,
    }
    if doi:
        payload["doi"] = doi
    if license:
        payload["license"] = license
    if expected_format:
        payload["expected_format"] = expected_format
    if manifest_path:
        payload["manifest_path"] = str(manifest_path.relative_to(project_root()))
        payload["manifest_available"] = manifest_path.exists()
    if metadata:
        payload["metadata"] = metadata
    return payload


