def data_sources_summary(sources: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    records = sources if sources is not None else data_sources_list()
    by_category: dict[str, int] = {}
    for source in records:
        category = str(source["category"])
        by_category[category] = by_category.get(category, 0) + 1
    return {
        "core_demo_sources": [source["id"] for source in records if source["category"] == "core_demo"],
        "public_dataset_adapters": [source["id"] for source in records if source["category"] == "public_dataset"],
        "facility_connector_stubs": [source["id"] for source in records if source["category"] == "facility_connector"],
        "artifact_standards": [source["id"] for source in records if source["category"] == "artifact_standard"],
        "validation_standards": [source["id"] for source in records if source["category"] == "validation_standard"],
        "future_extensions": [source["id"] for source in records if source["category"] == "future_extension"],
        "active_sources": [source["id"] for source in records if source.get("active")],
        "counts_by_category": by_category,
        "no_real_hardware": True,
        "no_runtime_downloads": True,
        "no_external_runtime_calls": True,
        "evidence_bundle_includes_registry": True,
    }


def data_sources_registry() -> dict[str, Any]:
    sources = data_sources_list()
    return {
        "registry_version": DATA_SOURCE_REGISTRY_VERSION,
        "generated_at": _now(),
        "safety_disclosure": FEDERATED_SAFETY_DISCLOSURE,
        "sources": sources,
        "summary": data_sources_summary(sources),
    }
